interface RemainingRosaryAudioOptions {
  currentTrackIndex: number;
  currentTrackPosition: number;
  durations?: Readonly<Record<string, number>>;
  remainingAudioPaths: readonly string[];
}

/** Totals the exact bundled recording duration for an ordered Rosary audio sequence. */
export function getRosaryAudioDurationSeconds(
  audioPaths: readonly string[],
  durations: Readonly<Record<string, number>> = ROSARY_AUDIO_DURATIONS,
) {
  const durationSeconds = audioPaths.reduce((total, path) => total + Math.max(0, durations[path] ?? 0), 0);
  return Math.max(0, Math.ceil(durationSeconds));
}

/** Formats an exact Rosary audio duration as minutes and seconds, including hours when necessary. */
export function formatRosaryAudioDuration(totalSeconds: number) {
  const seconds = Math.max(0, Math.ceil(Number.isFinite(totalSeconds) ? totalSeconds : 0));
  const hours = Math.floor(seconds / 3600);
  const minutes = Math.floor((seconds % 3600) / 60);
  const remainingSeconds = seconds % 60;
  const paddedMinutes = String(minutes).padStart(2, "0");
  const paddedSeconds = String(remainingSeconds).padStart(2, "0");

  return hours > 0 ? `${hours}:${paddedMinutes}:${paddedSeconds}` : `${minutes}:${paddedSeconds}`;
}

/**
 * Calculates the whole-second playback time left in the active Rosary, including later prayer queues.
 * Unknown recordings are excluded so unavailable files never inflate the estimate.
 */
export function getRemainingRosaryAudioSeconds({
  currentTrackIndex,
  currentTrackPosition,
  durations = ROSARY_AUDIO_DURATIONS,
  remainingAudioPaths,
}: RemainingRosaryAudioOptions) {
  const firstRemainingTrackIndex = Number.isFinite(currentTrackIndex) ? Math.max(0, Math.floor(currentTrackIndex)) : 0;
  const safeCurrentTrackPosition = Number.isFinite(currentTrackPosition) ? Math.max(0, currentTrackPosition) : 0;
  const remainingPaths = remainingAudioPaths.slice(firstRemainingTrackIndex);
  const durationSeconds = remainingPaths.reduce((total, path, index) => {
    const duration = durations[path] ?? 0;
    const elapsed = index === 0 ? safeCurrentTrackPosition : 0;
    return total + Math.max(0, duration - elapsed);
  }, 0);

  return Math.max(0, Math.ceil(durationSeconds));
}
